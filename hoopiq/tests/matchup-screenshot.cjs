const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const importer=require("../matchup-screenshot.js");
assert(importer.validWeek("2026-11-16"));
assert(!importer.validWeek("2026-11-17"));
assert.deepEqual(importer.extractTotals("Week 5\n WOMEN APPRECIATORS\n1489.00\n0/43"),{points:"1489.00",games:"0/43",week:"5"});
assert.deepEqual(importer.extractTotals("ALEX SARR THE GOAT\n1456.73\n0/45"),{points:"1456.73",games:"0/45",week:""});
const html=fs.readFileSync("hoopiq/index.html","utf8");
assert(html.includes('src="/matchup-screenshot.js?v=1"'));
assert(html.includes("matchupSnapshots:{}"));
assert(html.includes("loadRosterForOCR,updateNBA,loadWeek,route,$"));
const page=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).filter(Boolean).pop();
new vm.Script(page,{filename:"index.html"});
const matcher=fs.readFileSync("hoopiq/matchup-hq.js","utf8");
new vm.Script(matcher,{filename:"matchup-hq.js"});
assert(matcher.includes("window.HoopIQWeeklyImport?.render(c)"));
assert(matcher.includes("window.HoopIQWeeklyImport?.onClick(c,a,el)"));
assert(matcher.includes("window.HoopIQWeeklyImport?.onChange(c,t)"));
assert(matcher.includes("imported?.incomplete"));
const s=importer.session;
const player=(id,name,team,slot)=>({id,name,team,slot,confidence:100});
s.home=[player(1,"Player One","SAS","PG:1"),player(2,"Player Two","TOR","C:1")];
s.away=[player(3,"Player Three","WAS","SG:1"),player(4,"Player Four","DET","C:1")];
s.week="2026-11-16";s.weekNumber="5";s.homeName="WOMEN APPRECIATORS";s.awayName="ALEX SARR THE GOAT";
s.homeProjection="1489.00";s.awayProjection="1456.73";s.homeGames="0/43";s.awayGames="0/45";
let saved=0,rendered=0;
const state={roster:[100],opponentRoster:[200],rosterPositions:{100:"BN"},opponentPositions:{200:"IL"},
 matchupSnapshots:{},weekStart:"2026-11-09",scoring:{pts:1}};
const c={state,weekInfo:{start:"2026-11-09"},$:()=>null,render:()=>rendered++,
 persist:()=>saved++,toast:()=>{},loadWeek:()=>{},card:(title,body)=>"<div>"+title+body+"</div>",
 button:(action,label)=>"<button>"+label+"</button>",nbaPlayers:[],players:[]};
importer.save(c);
assert.equal(saved,1);
assert.equal(state.weekStart,"2026-11-16");
assert.equal(state.matchupSnapshots["2026-11-16"].homeProjection,1489);
assert.equal(state.matchupSnapshots["2026-11-16"].awayProjection,1456.73);
assert.equal(state.matchupSnapshots["2026-11-16"].homeGames,"0/43");
assert.equal(state.matchupSnapshots["2026-11-16"].awayGames,"0/45");
assert.equal(state.matchupSnapshots["2026-11-16"].source,"yahoo-screenshot");
assert.equal(state.matchupSnapshots["2026-11-16"].incomplete,true);
assert.deepEqual(state.roster,[100],"active team must never change");
assert.deepEqual(state.opponentRoster,[200],"opponent roster must never change");
assert.equal(state.scoring.pts,1);
const card=importer.render(c);
assert(card.includes("WOMEN APPRECIATORS")&&card.includes("ALEX SARR THE GOAT"));
assert(card.includes("1,489.00")&&card.includes("1,456.73"));
assert(card.includes("Import Yahoo matchup"));
assert(!card.includes("0.00</strong>"),"avoid fabricated current points");
console.log("Yahoo matchup screenshot snapshot tests passed (week, games, projected FP, no roster overwrite).");
